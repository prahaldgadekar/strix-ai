"""
brain/planner.py — STRIX v4.0
================================
TaskPlanner: converts ANY natural language request into a
structured JSON plan that executor.py can run step by step.

How it works:
  1. User says something complex
  2. brain_core detects it's a multi-step task
  3. TaskPlanner asks llama3.1 to break it into JSON steps
  4. executor.py runs each step in order

Supported actions in plans:
  create_folder_path   — create folder at any path (not just desktop)
  create_file_at_path  — create file at any path with content
  create_desktop_folder
  create_desktop_file
  open_app
  get_system_status
  get_weather
  get_news
  llm_response         — ask LLM a question as part of a plan

Example:
  User: "Create folder E:\\MyWebsite with HTML CSS JS files"
  Plan:
    step 1 → create_folder_path  E:\\MyWebsite
    step 2 → create_file_at_path E:\\MyWebsite\\index.html  (with starter HTML)
    step 3 → create_file_at_path E:\\MyWebsite\\style.css   (with starter CSS)
    step 4 → create_file_at_path E:\\MyWebsite\\script.js   (with starter JS)
"""

